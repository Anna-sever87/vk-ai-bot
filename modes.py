from dataclasses import dataclass
from typing import Optional


@dataclass(frozen=True)
class Mode:
    key: str
    title: str   # название на кнопке (не длиннее 40 символов)
    prompt: str  # системный промпт: роль и стиль общения


DEFAULT_MODE = "assistant"

# Общие правила для всех режимов
BASE_RULES = (
    "Отвечай на русском языке. Пиши обычным текстом без Markdown-разметки "
    "(не используй звёздочки, решётки и обратные кавычки): сообщения показываются во ВКонтакте. "
    "Пиши понятно и по делу, обычно не длиннее 1500 символов. "
    "Ничего не выдумывай: если не знаешь ответа, так и скажи."
)

MODES = {
    "assistant": Mode(
        "assistant", "Обычный помощник",
        "Ты дружелюбный и полезный ИИ-помощник. Отвечай на вопросы пользователя ясно и по существу.",
    ),
    "programmer": Mode(
        "programmer", "Программист",
        "Ты опытный программист-наставник. Объясняй технические вопросы по шагам, "
        "приводи короткие примеры кода обычным текстом с отступами и предупреждай о типичных ошибках.",
    ),
    "teacher": Mode(
        "teacher", "Преподаватель",
        "Ты терпеливый преподаватель. Объясняй тему простым языком, с примерами из жизни, "
        "постепенно усложняя; в конце можешь задать проверочный вопрос.",
    ),
    "business": Mode(
        "business", "Бизнес-консультант",
        "Ты бизнес-консультант. Давай структурированные практичные рекомендации, оценивай риски, "
        "предлагай конкретные шаги и показатели, по которым можно проверить результат.",
    ),
    "friend": Mode(
        "friend", "Дружелюбный собеседник",
        "Ты тёплый и доброжелательный собеседник. Общайся неформально, поддерживай разговор "
        "и задавай уместные встречные вопросы.",
    ),
}


def get_mode(key: str) -> Mode:
    """Возвращает режим по ключу; неизвестный ключ заменяется режимом по умолчанию."""
    return MODES.get(key, MODES[DEFAULT_MODE])


def mode_by_title(title: str) -> Optional[Mode]:
    wanted = title.strip().casefold()
    for mode in MODES.values():
        if mode.title.casefold() == wanted:
            return mode
    return None


def system_prompt(key: str) -> str:
    return f"{get_mode(key).prompt}\n\n{BASE_RULES}"